import json
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
WL = {"adcs": "ADCS attitude controller (binary64)", "ccsds": "CCSDS packet header (integer)",
      "crc16": "CRC-16-CCITT frame check (loop + array)", "px4": "PX4 rate controller (binary32, stateful)",
      "fbw": "Fighter fly-by-wire pitch channel (triplex voting, gain schedule, anti-windup; binary32)",
      "bdot": "CubeSat B-dot detumbling (frame rotation, filter; binary32)",
      "lander": "Mars lander terminal descent and touchdown detection (Suspect, Latch; binary32)"}
TG = {"rv32": "RV32IMAC", "r5": "Cortex-R5F", "leon3": "LEON3"}
VARIANTS = ["C (GCC)", "C (Clang)", "Ada", "SPARK", "Rust", "Rust+ovf", "Spelf (GCC)", "Spelf (Clang)"]
PAIRS = [("Spelf (GCC)", "C (GCC)"), ("Spelf (GCC)", "Ada"), ("Spelf (GCC)", "SPARK"),
         ("Spelf (Clang)", "C (Clang)"), ("Spelf (Clang)", "Rust"), ("Spelf (Clang)", "Rust+ovf")]

def gmean(xs):
    xs = [x for x in xs if x and x > 0]
    return math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else None

SC_TITLE = {"fbw": "Fighter fly-by-wire (statically unstable airframe, 80 Hz, 20 s)",
            "bdot": "3U CubeSat B-dot detumbling (10 Hz, 1 hour)",
            "lander": "Mars lander terminal descent (100 Hz, 40 s)"}

def _fmt(v):
    if isinstance(v, float):
        return f"{v:.3f}"
    return "—" if v is None else str(v)

def complex_sil_section():
    p = HERE / "sil_complex_results.json"
    if not p.exists():
        return []
    sc = json.loads(p.read_text(encoding="utf-8"))
    cells = [c for s in sc.values() for c in s.get("cells", {}).values() if c.get("status") == "ok"]
    same = sum(1 for c in cells if c["bit_identical"])
    L = ["## Complex systems in closed loop (SIL): fighter, CubeSat, Mars lander\n",
         "Generated by `python sil_complex.py`. The plant is in C (the same object for every variant), the controller is each language's own "
         "compiled object, and the whole loop runs on the target ISA. Reference: the same plant in Python + the controller in the spelfc "
         f"interpreter. **{same} / {len(cells)}** variant-target-scenario triples produced a trajectory bit-identical to the "
         "reference.\n"]
    for k, s in sc.items():
        ref = s["reference"]
        L.append(f"### {SC_TITLE.get(k, k)}\n")
        L.append("Reference result: " + ", ".join(f"`{a}` = {_fmt(b)}" for a, b in ref.items() if not isinstance(b, list))
                 + "\n")
        L.append("| Variant | " + " | ".join(TG[t] for t in TG) + " |")
        L.append("|---|---|---|---|")
        for v in VARIANTS:
            row = []
            for t in TG:
                c = s.get("cells", {}).get(f"{v} | {t}", {})
                row.append("—" if c.get("status") != "ok" else ("same ✓" if c["bit_identical"] else "DIFFERENT ✗"))
            L.append(f"| {v} | " + " | ".join(row) + " |")
        L.append("")
    L += ["### Real defect mutants: the same defect in four languages\n",
          "Each mutant was written the same way in C, Rust, Ada/SPARK and Spelf. The C version was flown in closed loop in the same "
          "scenario (RV32). Static columns: whether the tool accepted the mutant and whether it gave a **new** diagnostic compared with the base version.\n",
          "| Mutant | Class | C closed-loop result | GCC -fanalyzer | Cppcheck MISRA | rustc + Clippy | GNATprove | Spelf |",
          "|---|---|---|---|---|---|---|---|"]
    for k, s in sc.items():
        for mid, m in s.get("mutants", {}).items():
            cl = m["c_closed_loop"]
            if k == "fbw":
                out = (f"max α {cl['max_alpha_deg']:.1f}°" + (", **LOSS OF CONTROL**" if cl["departed"] else "")
                       + f"; post-gust q peak {cl['post_gust_q_peak_dps']:.1f}°/s (reference "
                       f"{s['reference']['post_gust_q_peak_dps']:.1f})")
            elif k == "bdot":
                out = (f"{cl['final_rate_dps']:.2f}°/s after 1 hour (reference {s['reference']['final_rate_dps']:.2f}); "
                       + ("never below 1°/s" if cl["t_below_1dps"] is None else f"below 1°/s at t = {cl['t_below_1dps']:.0f} s"))
            else:
                out = (f"engines cut at {cl['engine_cut_alt']:.0f} m, impact {abs(cl['touchdown_v']):.1f} m/s: "
                       f"**{cl['outcome']}**")
            st = m.get("static", {})

            def cell(name):
                x = st.get(name, {})
                if "tool" in x:
                    return "tool missing"
                if not x:
                    return "—"
                if not x.get("accepted"):
                    return "rejected"
                return "accepted, new diagnostic: " + "; ".join(x["new_diagnostics"])[:80] if x.get("n_new") else "accepted, no diagnostic"
            sp = m["spelf"]
            spv = "accepted (cannot be caught)" if sp["accepted"] else f"**ret [{sp['rule']}]**"
            gp = st.get("Ada: GNATprove (AoRTE)", {})
            gpv = ("AoRTE proved, no diagnostic" if gp.get("proved_clean") else cell("Ada: GNATprove (AoRTE)")) if gp else "—"
            L.append(f"| {mid}: {m['title']} | {m['class']} | {out} | {cell('C: GCC -fanalyzer')} | "
                     f"{cell('C: Cppcheck MISRA')} | {cell('Rust: rustc + Clippy')} | {gpv} | {spv} |")
    L += ["",
          "**Reading.** Spelf rejects four of the five real defect classes (windup, frame, latched transient, sensor status) "
          "at compile time; the compilers and static tools of the competing languages reject none of them "
          "(Cppcheck's \"unused struct member\" warning on LND-M2 is an indirect hint). GNATprove proves these mutants "
          "**free of run-time errors**, correctly: none of them is an overflow or a range error, "
          "yet the vehicle still crashes or loses control. The fifth mutant (mean instead of median) is an algorithm "
          "error; no language rule catches it, Spelf's included, which is why it is in the table.\n"]
    return L

def main():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except AttributeError:
            pass
    r = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
    sil = json.loads((HERE / "sil_results.json").read_text(encoding="utf-8")) if (HERE / "sil_results.json").exists() else None
    cells_all = [(wl, k, c) for wl in r for k, c in r[wl]["cells"].items()]
    ok = [c for _, _, c in cells_all if c.get("status") == "ok"]
    eq = sum(1 for c in ok if c["equal"])
    L = ["# Spacecraft workloads: four languages, three flight ISAs, measured with real tools\n",
         "Generated by `python run.py && python sil.py && python report.py`. Raw data: `results.json`, `sil_results.json`.\n",
         "## What was measured\n",
         "Flight software workloads were written **with the same algorithm and the same order of operations** in C, Ada/SPARK, Rust and Spelf "
         "(`src/`). Each was compiled with real cross compilers and flight flags (-O2, freestanding) and "
         "run in the Unicorn emulator with the matching CPU model:\n",
         "| Variant | Compiler | Note |\n|---|---|---|",
         "| C (GCC) / C (Clang) | GCC 16.1 (GNAT cross) / Clang (Zig) | flight-permitted C: MISRA style, no run-time checks |",
         "| Ada | GCC 16.1 (GNAT) | run-time checks on (range, overflow, index) |",
         "| SPARK | GCC 16.1 (GNAT) | the same Ada source, AoRTE proved with GNATprove `--level=2` → `-gnatp` |",
         "| Rust / Rust+ovf | rustc 1.98 (LLVM) | `no_std`, release; overflow checks off / on (bounds checks always) |",
         "| Spelf (GCC) / Spelf (Clang) | spelfc → GCC 16.1 / Clang | proved C, no run-time checks |\n",
         "Targets: **RV32IMAC** (software floating point), **Cortex-R5F** (Thumb-2 + VFPv3-D16, hard-float ABI), "
         "**LEON3** (SPARC V8, hardware FPU; C and Spelf only, since no GNAT or Rust SPARC cross compiler was available in this "
         "setup).\n",
         "For each cell: bit-for-bit agreement of the outputs with the **reference semantics** (spelfc interpreter); instructions "
         "executed per call (mean / worst; not WCET, but relative cost on the same processor); `.text` size of the workload "
         "object; worst-case stack from the target assembly (external library calls excluded); the number of **run-time "
         "checks** left in the compiled code (panic / `__gnat_rcheck` call sites).\n",
         f"## Correctness: {eq} / {len(ok)} cells bit-identical to the reference\n"]
    if sil:
        sok = [c for c in sil["cells"].values() if c.get("status") == "ok"]
        sid = sum(1 for c in sok if c["bit_identical"])
        ref = sil["reference"]
        conv = next((t for t, e, _ in ref if e < 1.0), None)
        L += [f"Closed-loop spacecraft test (below): **{sid} / {len(sok)}** variant-target pairs produced a trajectory bit-identical to "
              f"the Python reference simulation.\n"]
    for wl in r:
        res = r[wl]
        spark = res.get("spark", {})
        L.append(f"## {WL.get(wl, wl)}\n")
        L.append(f"{res['calls']} calls · Spelf: **{res.get('spelf_obligations', '?')} proof obligations** · "
                 f"GNATprove: {'clean, ' + str(spark.get('checks')) + ' checks proved' if spark.get('clean') else spark.get('messages', '—')}\n")
        targets = [t for t in TG if any(k.endswith("| " + t) for k in res["cells"])]
        L.append("| Variant | " + " | ".join(f"{TG[t]}: instr. mean / worst" for t in targets) + " | " +
                 " | ".join(f"{TG[t]}: .text B · stack B" for t in targets) + " | checks left | equal |")
        L.append("|---|" + "---|" * (2 * len(targets) + 2))
        for v in VARIANTS:
            ins, siz, chk, eqs = [], [], set(), set()
            for t in targets:
                c = res["cells"].get(f"{v} | {t}", {})
                if c.get("status") != "ok":
                    ins.append("—")
                    siz.append("—")
                    continue
                ins.append(f"{c['insn_mean']:g} / {c['insn_max']}")
                siz.append(f"{c['text']} · {c['stack'] if c['stack'] is not None else '?'}")
                chk.add(c["checks"])
                eqs.add(c["equal"])
            name = f"**{v}**" if v.startswith("Spelf") else v
            L.append(f"| {name} | " + " | ".join(ins) + " | " + " | ".join(siz) + " | "
                     + (", ".join(str(x) for x in sorted(chk)) or "—") + " | "
                     + ("✓" if eqs == {True} else ("✗" if False in eqs else "—")) + " |")
        L.append("")
    L.append("## Summary: Spelf relative to the others (geometric mean, same compiler back end)\n")
    L.append("| Comparison | instructions / call | .text | checks left in Spelf | checks left in the other (total) |")
    L.append("|---|---|---|---|---|")
    for a, b in PAIRS:
        ri, rs, ca, cb = [], [], 0, 0
        for wl in r:
            for t in TG:
                x, y = r[wl]["cells"].get(f"{a} | {t}", {}), r[wl]["cells"].get(f"{b} | {t}", {})
                if x.get("status") == "ok" and y.get("status") == "ok":
                    ri.append(x["insn_mean"] / y["insn_mean"])
                    rs.append(x["text"] / y["text"])
                    ca += x["checks"]
                    cb += y["checks"]
        gi, gs = gmean(ri), gmean(rs)
        if gi is None:
            continue
        L.append(f"| {a} ÷ {b} | **{gi:.3f}** ({(gi - 1) * 100:+.1f}%) | **{gs:.3f}** ({(gs - 1) * 100:+.1f}%) | {ca} | {cb} |")
    best_of = {"C": ["C (GCC)", "C (Clang)"], "Ada": ["Ada"], "SPARK": ["SPARK"], "Rust": ["Rust"],
               "Rust+ovf": ["Rust+ovf"], "Spelf": ["Spelf (GCC)", "Spelf (Clang)"]}
    L += ["", "### Each language with its best compiler: mean instructions per call (lower is better)\n",
          "| Workload · target | " + " | ".join(best_of) + " | best |",
          "|---|" + "---|" * (len(best_of) + 1)]
    wins = {k: 0 for k in best_of}
    for wl in r:
        for t in TG:
            vals = {}
            for lang, vs in best_of.items():
                xs = [r[wl]["cells"].get(f"{v} | {t}", {}) for v in vs]
                xs = [x["insn_mean"] for x in xs if x.get("status") == "ok"]
                vals[lang] = min(xs) if xs else None
            if sum(v is not None for v in vals.values()) < 2:
                continue
            best = min(v for v in vals.values() if v is not None)
            winners = [k for k, v in vals.items() if v is not None and v <= best * 1.005]
            for k in winners:
                wins[k] += 1
            L.append(f"| {wl} · {TG[t]} | " + " | ".join("—" if v is None else (f"**{v:g}**" if k in winners else f"{v:g}")
                                                       for k, v in vals.items()) + f" | {', '.join(winners)} |")
    L.append("")
    L.append("Number of cells where each is best (±0.5%): " + ", ".join(f"{k} {v}" for k, v in wins.items()) + ".\n")
    L += ["On RV32, most of the instructions of the floating-point workloads (ADCS, PX4) are in the software floating-point library; "
          "Rust links its own `compiler_builtins`, the others Zig's `compiler-rt`, so the difference in these cells is partly "
          "a library difference, not a language difference.\n"]
    sys.path.insert(0, str(HERE.parent / "multilang"))
    sys.path.insert(0, str(HERE.parent.parent / "compiler"))
    import d1_size as D
    src = HERE / "src"
    unit = {w: f"wl_{w}" for w in r}
    L += ["### Source size (tokens, without comments)\n", "| Workload | C | Ada/SPARK | Rust | Spelf | Spelf ÷ C |",
          "|---|---|---|---|---|---|"]
    for wl in r:
        c = D.toks_c((src / f"{wl}.c").read_text(encoding="utf-8"))
        a = D.toks_ada({f"{unit[wl]}.{e}": (src / f"{unit[wl]}.{e}").read_text(encoding="utf-8") for e in ("ads", "adb")})
        ru = D.toks_c((src / f"{wl}.rs").read_text(encoding="utf-8"))
        s = D.toks_spelf((src / f"{wl}.spelf").read_text(encoding="utf-8"))
        L.append(f"| {wl} | {c} | {a} | {ru} | {s} | {s / c:.2f} |")
    L.append("\nThe Spelf source carries units, ranges and proved contracts; the C source carries none of them. "
             "The Ada/SPARK source carries the same information as subtypes, preconditions and loop invariants.\n")
    L += ["",
          "**Reading.** Spelf compiles to C; on the same compiler back end, the machine code it produces is **as fast and as small** as hand-written "
          "flight C of the same algorithm and as SPARK with its checks proved and removed; the difference is at noise "
          "level (±1–2 instructions in some cells). It produces **fewer instructions and clearly smaller "
          "code** than Ada with run-time checks, because it proves at compile time the checks Ada performs at run time: the run-time "
          "checks left in Spelf are **zero**. The only other variant that achieves that is SPARK; but in the defect corpus SPARK "
          "catches 19 of the 26 classes and Spelf all 26 (see the multilang benchmark).\n",
          "Against Rust the picture is mixed and the difference comes from the toolchain, not the language: "
          "**C (Clang), compiling the same C source with the same Clang, gives the same numbers as Spelf (Clang)**. On RV32 Rust links its own software floating-point "
          "library (`compiler_builtins`), every other variant Zig's `compiler-rt`; Rust's "
          "10–23% advantage there is that library difference. On the Cortex-R5F, which has a hardware FPU, Spelf (Clang) and Rust are level (ahead on 3 "
          "workloads, equal on 2, behind on 2). Its code is clearly smaller than overflow-checked Rust's.\n"
          "",
          "Honest limit: Spelf is **not faster, and cannot be faster,** than unchecked C of the same algorithm; it produces that C. "
          "Spelf's claim is \"as fast as C, faster than Ada/Rust with safety checks, and proved\", not \"faster "
          "than C\". Instruction counts are not WCET (no caches, no pipeline); WCET measurement on hardware is future work.\n"]
    if sil:
        L += ["## Closed-loop spacecraft test (SIL): 6U CubeSat attitude manoeuvre\n",
              "Plant: rigid body, J = diag(0.05, 0.06, 0.04) kg·m², Euler equations + quaternion kinematics, RK4, "
              "dt = 0.1 s, 600 s. Start: **160°** about the axis (1, 2, 3) and a rate of (0.05, −0.04, 0.03) rad/s; target: the "
              "unit quaternion. **At t = 300 s the estimator flips the sign of its quaternion** (q → −q: same attitude). "
              "The plant is the same C object for every variant; the controller is each language's own object; the whole loop runs on the "
              "target ISA. Reference: the same plant in Python + the controller in the spelfc interpreter.\n",
              "| t [s] | pointing error [°] (reference) | |ω| [deg/s] |", "|---|---|---|"]
        for t, e, w in sil["reference"][::5]:
            L.append(f"| {t:g} | {e:.4f} | {w:.4f} |")
        L.append("")
        L.append("| Variant | " + " | ".join(TG[t] for t in TG) + " |")
        L.append("|---|---|---|---|")
        for v in VARIANTS:
            row = []
            for t in TG:
                c = sil["cells"].get(f"{v} | {t}", {})
                row.append("—" if c.get("status") != "ok" else ("bit-identical ✓" if c["bit_identical"] else "DIFFERENT ✗"))
            L.append(f"| {v} | " + " | ".join(row) + " |")
        m = sil.get("mutant", {})
        if m:
            rows = m["c_rows"]
            i_flip = len(rows) // 2
            L += ["",
                  f"**Controller without canonicalisation (mutant M-17, C, RV32):** identical to the reference until the sign flip "
                  f"(error {rows[i_flip - 1][1]:.3f}° at t = 300 s); after the flip, positive feedback drives the vehicle away from the target: "
                  f"largest deviation **{max(x[1] for x in rows[i_flip:]):.1f}°**, still "
                  f"{rows[-1][1]:.1f}° at 600 s (it has started the ≈ 360° long way round). It compiles and it flies.",
                  f"The same defect in Spelf: with the error quaternion written as a record carrying a canonical-form invariant "
                  f"(R-505) **{m['spelf']}**; the canonicalising counterpart: **{m.get('spelf_fixed', '?')}**.\n"]
    L += complex_sil_section()
    (HERE / "results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[-40:]))

if __name__ == "__main__":
    main()
