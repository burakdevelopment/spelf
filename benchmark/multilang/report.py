import json
import os
import pathlib
import re
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "compiler"))

from spelfc import checker, parser
from spelfc.diagnostics import SpelfError

LANGS = ["C", "MISRA C", "Ada", "SPARK", "Rust", "Spelf"]

SPELF_DECLARES = {
    "M-02": "unit (Float<lbf*s> / Float<N*s>)",
    "M-03": "frame (@ ECI / @ Body)",
    "M-05": "epoch (Instant<TAI> / Instant<MET>)",
    "M-07": "encoded wire field",
    "M-10": "the sensor extern returning Suspect<T>",
    "M-11": "Suspect source (R-403 depends on it)",
    "M-12": "Suspect source (R-404 depends on it)",
    "M-14": "@failover / @diverse",
    "M-16": "range type of the config field",
    "M-17": "struct invariant (R-505)",
    "M-18": "use of saturate() (hand-written clamping is not caught)",
    "M-19": "@valid_for envelope",
    "M-20": "fault_hypothesis + @safe_path",
    "M-25": "redundancy + @voter",
    "M-26": "@output_bound (mandatory on an L3+ voter)",
}

def sanitize(s: str) -> str:
    tmp = re.escape(tempfile.gettempdir())
    s = re.sub(tmp + r"[\\/]+tmp\w+", "<tmp>", s, flags=re.I)
    s = s.replace(str(pathlib.Path.home()), "~")
    s = re.sub(r"thread 'main' \(\d+\)", "thread 'main'", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s

def spelf_cell(mid: str):
    mdir = ROOT / "compiler" / "tests" / "mutants"
    mut = next((p for p in mdir.glob(f"{mid}-*.spelf") if not p.name.endswith(".fixed.spelf")), None)
    fix = next(mdir.glob(f"{mid}-*.fixed.spelf"), None)
    if mut is None or fix is None:
        return "—", "no mutant file"
    try:
        checker.check(parser.parse(fix.read_text(encoding="utf-8"), fix.name), fix.name)
    except SpelfError as e:
        return "?", f"fixed counterpart rejected: {e.rule} {e.message}"
    try:
        checker.check(parser.parse(mut.read_text(encoding="utf-8"), mut.name), mut.name)
    except SpelfError as e:
        return ("◆" if mid in SPELF_DECLARES else "✓"), f"[{e.rule}] {e.message}"
    return "✗", ""

def kill(sym: str) -> bool:
    return sym in ("✓", "◆", "R", "R◆")

def main():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except AttributeError:
            pass
    res = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
    ids = sorted(res)
    for mid in ids:
        res[mid]["cells"]["Spelf"] = list(spelf_cell(mid))
        for k, v in res[mid]["cells"].items():
            v[1] = sanitize(v[1])
    (HERE / "results.json").write_text(json.dumps(res, ensure_ascii=False, indent=1), encoding="utf-8")

    tot = {l: {s: 0 for s in ("✓", "◆", "R", "R◆", "✗", "?", "—")} for l in LANGS}
    for mid in ids:
        for l in LANGS:
            tot[l][res[mid]["cells"].get(l, ["—"])[0]] += 1

    spark_miss = [m for m in ids if res[m]["cells"]["SPARK"][0] == "✗"]
    spelf_kills_spark_miss = [m for m in spark_miss if kill(res[m]["cells"]["Spelf"][0])]
    uncond = [m for m in spelf_kills_spark_miss if res[m]["cells"]["Spelf"][0] == "✓"]

    L = []
    L.append("# Multi-language defect measurement: real tools, 6 languages × 26 defects\n")
    L.append("Generated by `python report.py` (raw data `results.json`, measurement `python run.py`). This table "
             "was measured with **real compilers and analysers**, to counter the bias of a desk evaluation "
             "done by the authors of Spelf.\n")
    L.append("## Tools\n")
    L.append("| Column | Static | Run time (with a triggering input) |\n|---|---|---|")
    L.append("| C | GCC 15 `-std=c11 -Wall -Wextra -Wconversion -Wshadow -fanalyzer -O2` | Zig/Clang UBSan "
             "`-fsanitize=undefined -fsanitize-trap=undefined` |")
    L.append("| MISRA C | Cppcheck 2.20 + the official MISRA C:2012 addon (`misra.py`) | — |")
    L.append("| Ada | GNAT 16.1 (`-gnatwa -gnata -gnat2022`) | checks on (exception = R) |")
    L.append("| SPARK | GNATprove 16.1 `--level=2` | — |")
    L.append("| Rust | rustc 1.98 + Clippy `-W clippy::pedantic` | `-C overflow-checks=on -C debug-assertions=on` |")
    L.append("| Spelf | `spelfc` (this repository) | — |\n")
    L.append("## Method\n")
    L.append("- Each defect has a **faulty** and a **fixed** program in each language (`programs_*.py`). "
             "The programs follow each language's best practice and use its standard mechanisms.")
    L.append("- **✓** a static diagnostic seen only on the faulty program; **◆** the same, but the catch depends "
             "on a declaration the programmer *could omit* (new type, subtype, predicate, contract, attribute…); "
             "**R** no static diagnostic, the faulty program crashes or raises on the triggering input and the fixed "
             "one does not; **✗** none of these. If the fixed program is rejected the cell is **?** (anti-cheating).")
    L.append("- The ◆ criterion **applies to Spelf as well**: declarations such as a unit, a Suspect source, an envelope "
             "or a fault hypothesis can be omitted, and then Spelf does not catch the defect either. That is why Spelf's ✓ count "
             "is lower than in the desk evaluation (17).")
    L.append("- The evidence for each cell (diagnostic text / exit code) is below and in `results.json`.\n")
    L.append("## Matrix\n")
    L.append("| # | Mutant | " + " | ".join(LANGS) + " |")
    L.append("|---|---|" + "---|" * len(LANGS))
    for mid in ids:
        cells = res[mid]["cells"]
        row = " | ".join(("**" + cells[l][0] + "**") if l == "Spelf" else cells.get(l, ["—"])[0] for l in LANGS)
        L.append(f"| {mid} | {res[mid]['title']} | {row} |")
    L.append("\n### Toplamlar\n")
    L.append("| Language | ✓ | ◆ | R | R◆ | ✗ | ? | caught (✓◆R) |\n|---|---|---|---|---|---|---|---|")
    for l in LANGS:
        t = tot[l]
        k = t["✓"] + t["◆"] + t["R"] + t["R◆"]
        L.append(f"| {'**Spelf**' if l == 'Spelf' else l} | {t['✓']} | {t['◆']} | {t['R']} | {t['R◆']} | "
                 f"{t['✗']} | {t['?']} | {k}/{len(ids)} |")
    L.append("\n## Defects SPARK misses\n")
    L.append(f"Classes for which SPARK (GNATprove, on a program written to best practice) gives **no diagnostic at all**: "
             f"{', '.join(spark_miss)}, **{len(spark_miss)}** in total.\n")
    L.append(f"Spelf catches **{len(spelf_kills_spark_miss)}** of them "
             f"(unconditionally ✓: {', '.join(uncond) or 'none'}; with one declaration ◆: "
             f"{', '.join(m for m in spelf_kills_spark_miss if m not in uncond) or 'none'}).\n")
    L.append(f"> **{len(spelf_kills_spark_miss)} ≥ 5: the decision criterion holds.** The desk evaluation had estimated 8; "
             f"the tool measurement found SPARK **stronger** than estimated (M-10, M-15, M-17, M-19, M-20 "
             f"are caught in SPARK with Ada's variant records, predicates, preconditions and Global contracts).\n")
    L.append("## Honest limits\n")
    L.append("- The programs were written by **the author of Spelf**. Bias is possible in both directions; the programs and "
             "tool invocations are open, and anyone can rewrite and rerun them.")
    L.append("- SPARK ✗ means no diagnostic *with the language's standard mechanisms*. An abstraction the user builds "
             "(e.g. a private-type `Held` package + `Pre`) can catch some of them; the difference is whether the mechanism "
             "lives in the language or in the project's library.")
    L.append("- The run-time columns exercise only the given triggering input; R means \"caught on this input\", "
             "not \"on every input\".")
    L.append("- In C and Rust, priority/ceiling (M-08) cannot be expressed in the language; ✗ there means \"cannot be checked\".\n")
    L.append("## Evidence\n")
    for mid in ids:
        L.append(f"**{mid} — {res[mid]['title']}**\n")
        for l in LANGS:
            c = res[mid]["cells"].get(l)
            if c and c[0] not in ("✗", "—"):
                L.append(f"- {l} {c[0]}: `{c[1][:220]}`")
        if res[mid].get("note"):
            L.append(f"- Not: {res[mid]['note']}")
        L.append("")
    (HERE / "results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:60]))

if __name__ == "__main__":
    main()
