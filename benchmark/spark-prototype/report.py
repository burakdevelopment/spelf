import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent

SPELF = {
    "L-10a": "◆ R-402 (`Suspect` extern return)",
    "L-11b": "◆ R-403: even without Held, a sensor-derived value cannot be written to `state` (provenance tracking)",
    "L-11c": "◆ R-403 (the same program is rejected in Spelf; no contract needed)",
    "L-12b": "◆ R-404: a sensor-derived condition cannot change a persistent `bool`",
    "L-18a": "◆ R-407 (`Clamped` cannot be used in place of T)",
    "L-24b": "✓ 05§5.1: a `Fix` scale change only through `requantize<…>(x, rounding = …)`",
}

def main():
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except AttributeError:
            pass
    r = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
    L = ["# SPARK prototype: Spelf mechanisms as a SPARK library\n",
         "Generated by `python run.py && python report.py`. Tool: GNATprove 16.1 `--level=2` (cvc5, Z3, Alt-Ergo).\n",
         "## Question\n",
         "The alternative to a new language: could Spelf offer its ideas to SPARK as a **library + rules** "
         "instead? The mechanisms Spelf uses for the classes SPARK misses (`Suspect`, `Held`, `Latch`, "
         "`Clamped`, explicit rounding) were written as well as we could as the package `spelf_mech`, and for each class a "
         "faulty and a fixed program using the library were run through GNATprove.\n",
         "Two separate questions were measured: **(a)** is a program that uses the library but misuses it caught "
         "(the strength of the library), **(b)** is a program that does not use the library at all caught (whether the rule is mandatory).\n",
         f"The library itself: **{'clean under GNATprove, absence of run-time errors proved' if r['library_clean'] else 'there are unproved checks (see the run.py output)'}**.\n",
         "## Result\n",
         "| Case | Question | SPARK + library | Evidence | The same defect in Spelf |",
         "|---|---|---|---|---|"]
    for cid, c in r["cases"].items():
        L.append(f"| {cid} {c['title']} | ({c['question']}) | **{c['verdict']}** | `{c['evidence'][:90] or '—'}` | "
                 f"{SPELF.get(cid, '')} |")
    L += ["",
          "## Reading\n",
          "1. **Rules that wrap a value can be carried by a library.** With `Suspect` and `Clamped` written as discriminated "
          "records, reading the value without checking the tag is a discriminant-check error in GNATprove (L-10a, L-18a: "
          "◆). For these classes the SPARK-library route really is enough.",
          "2. **Rules about obligation and provenance cannot be carried.** Spelf's R-403/R-404 reject a program that does *not* use "
          "the library: a value derived from a sensor, whatever it passes through (local variable, return value, branch "
          "condition), cannot enter persistent state without an age limit. In SPARK these programs pass cleanly (L-11b, L-12b: "
          "✗). Explicit rounding cannot be made mandatory either: with the library's `Requantize` available, an implicit conversion is still legal "
          "(L-24b: ✗).",
          "3. **Information-flow contracts cannot express age.** SPARK's `Depends` contract checks the *existence* "
          "of a dependency. The program with Held and the one without depend on the sensor in the same way; with an honest "
          "contract on both, they cannot be told apart (L-11c: ✗). The difference is a temporal property (age, persistence), "
          "not a flow property.",
          "4. For the architectural and temporal rules (R-405 diversity, R-412 Byzantine thresholds, R-605 output bound under "
          "faults) no library counterpart could be designed: they need the call graph, an architecture declaration and bounded-horizon model "
          "checking.\n",
          "**Conclusion:** some of Spelf's rules can be offered to SPARK as a library (and should be: for teams using SPARK today "
          "it is the quickest gain). The part that carries the thesis of the project, the rules that make engineering decisions "
          "**mandatory** and track provenance, has to live in the language. This supports the "
          "decision to build a language rather than a library.\n",
          "## Honest limits\n",
          "- The library and the programs were written by the author of Spelf. A more inventive SPARK design (e.g. abstract data "
          "types that never hand out the sensor value, age tracking with ghost code) could turn some ✗ into ◆; "
          "that would mean putting the library on the user as a **design discipline**.",
          "- The cases are small; the aim is to see whether the mechanism can be expressed, not how it scales.",
          "- In the case runs the library body is not proved again (`SPARK_Mode => Off`); the body is proved in a separate "
          "run. The cases see only the library's contracts, as a user would.",
          ""]
    (HERE / "results.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:20]))

if __name__ == "__main__":
    main()
